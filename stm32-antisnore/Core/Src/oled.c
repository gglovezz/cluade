static uint8_t cmd(uint8_t c) {
    return HAL_I2C_Mem_Write(s_i2c, OLED_I2C_ADDR, 0x00, I2C_MEMADD_SIZE_8BIT, &c, 1, 50);
}
static uint8_t data(uint8_t d) {
    return HAL_I2C_Mem_Write(s_i2c, OLED_I2C_ADDR, 0x40, I2C_MEMADD_SIZE_8BIT, &d, 1, 50);
}

void OLED_Init(I2C_HandleTypeDef *hi2c) {
    s_i2c = hi2c;
    HAL_Delay(200);
    cmd(0xAE); /* display off */
    cmd(0xD5); cmd(0x80); /* clock */
    cmd(0xA8); cmd(0x3F); /* multiplex */
    cmd(0xD3); cmd(0x00); /* offset */
    cmd(0x40); cmd(0x00); /* start line */
    cmd(0x8D); cmd(0x14); /* charge pump */
    cmd(0x20); cmd(0x00); /* memory addr mode: page */
    cmd(0xA1);             /* seg remap */
    cmd(0xC8);             /* COM scan dir */
    cmd(0xDA); cmd(0x12); /* COM pins */
    cmd(0x81); cmd(0xCF); /* contrast */
    cmd(0xD9); cmd(0xF1); /* pre-charge */
    cmd(0xDB); cmd(0x40); /* VCOMH */
    cmd(0xA4);             /* display follows RAM */
    cmd(0xA6);             /* normal */
    cmd(0xAF);             /* display ON */
    OLED_Clear(); OLED_Update();
}

void OLED_Clear(void) { memset(OLED_BUF, 0, sizeof(OLED_BUF)); }

void OLED_Update(void) {
    for (int page = 0; page < 8; page++) {
        cmd(0xB0 + page);
        cmd(0x00); cmd(0x10);
        for (int x = 0; x < OLED_W; x++) data(OLED_BUF[page][x]);
    }
}

void OLED_DrawPixel(int x, int y, uint8_t on) {
    if (x<0||x>=OLED_W||y<0||y>=OLED_H) return;
    int page = y / 8;
    int bit  = y % 8;
    if (on)  OLED_BUF[page][x] |=  (1 << bit);
    else     OLED_BUF[page][x] &= ~(1 << bit);
}

/* 8×16 字形: 两页高, 共16字节
   g[0..7]  → 上半页 (y .. y+7), 每行一个字节 (8bit = 8列)
   g[8..15] → 下半页 (y+8 .. y+15)
   位序: MSB=最左列
*/
static void draw_char_8x16(int x, int y, char c) {
    const uint8_t *g = NULL;
    if (c >= '0' && c <= '9')      g = FONT8x16_DIGITS[c-'0'];
    else if (c >= 'A' && c <= 'Z') g = FONT8x16_LETTERS[c-'A'];
    else if (c == ' ')             g = NULL;   /* 空格留空 */
    if (!g) return;
    for (int page = 0; page < 2; page++) {
        for (int row = 0; row < 8; row++) {
            uint8_t col_data = g[page * 8 + row];
            for (int col = 0; col < 8; col++) {
                uint8_t bit = (col_data >> (7 - col)) & 1;
                OLED_DrawPixel(x + col, y + page * 8 + row, bit);
            }
        }
    }
}
void OLED_DrawString(int x, int y, const char *s) {
    while (*s && x < OLED_W - 8) {
        draw_char_8x16(x, y, *s);
        x += 8; s++;
    }
}
